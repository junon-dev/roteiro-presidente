    /** Substitui {chave} pelos valores. */
    fun formatar(modelo: String, vararg pares: Pair<String, Any?>): String {
        var s = modelo
        for ((k, v) in pares) s = s.replace("{" + k + "}", v?.toString() ?: "?")
        return s
    }
